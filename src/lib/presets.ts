export interface LocalRecipe {
  /** 基础 CSS 滤镜微调（与像素级 filmGrade 协同） */
  brightness: number; // 1 = normal
  contrast: number; // 1 = normal
  saturate: number; // 1 = normal
  sepia?: number;
  hueRotate?: number;
  /** 像素级胶片色彩科学调色配置 */
  filmGrade?: FilmGrade;
  overlayGradient?: {
    from: string;
    to: string;
    blendMode: GlobalCompositeOperation;
    opacity: number;
  };
  /** 柔光 / 黑柔 Pro-Mist 光晕 (0~1) */
  bloom?: number;
  /** 胶片红橙高光光晕溢色 (类似 CineStill 800T / 怀旧负片 Halation) */
  halationColor?: string;
  halationStrength?: number;
  vignette?: number; // 0~1 edge darkening
  grain?: number; // 0~1 film grain
  edgeBokeh?: number; // 0~1 radial soft blur around edges
  recommendedTopBreathing?: number; // 0~0.35
}

